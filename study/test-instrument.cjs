'use strict';
const assert = require('node:assert/strict');
const core = require('./instrument-core.js');
assert.equal(core.assign(0), 'unaided');
assert.equal(core.assign(0.4999), 'unaided');
assert.equal(core.assign(0.5), 'reference_aided');
assert.equal(core.assign(0.9999), 'reference_aided');
assert.throws(() => core.assign(1));
assert.equal(core.recommendation(0), 'central');
assert.equal(core.recommendation(100), 'garden');
assert.throws(() => core.recommendation(NaN));
assert.throws(() => core.recommendation(-1));
assert.equal(new Set(core.OPTIONS.map(o => o.id)).size, 3);
const valid = {record_type: 'instrument_preview_not_human_evidence', human_participation_verified: false, assignment: {arm: 'unaided'}, choice: {option_id: 'garden'}, config: {mode: 'preview_only'}};
assert.equal(core.validateExport(valid), true);
assert.throws(() => core.validateExport({...valid, human_participation_verified: true}));
assert.throws(() => core.validateExport({...valid, record_type: 'human_participant'}));
assert.throws(() => core.validateExport({...valid, config: {mode: 'participant'}}));
console.log('14 offline instrument assertions passed.');
